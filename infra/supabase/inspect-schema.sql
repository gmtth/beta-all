-- Inspecao somente leitura do schema beta para preparar migrations reproduziveis.
-- Execute no SQL Editor do projeto Supabase e exporte apenas o resultado desta consulta.
-- Nao retorna linhas de source_record/record_chunk; retorna definicoes e metadados de catalogo.
WITH target_tables AS (
  SELECT c.oid, n.nspname AS schema_name, c.relname AS table_name,
         c.relrowsecurity, c.relforcerowsecurity, c.relowner
  FROM pg_catalog.pg_class c
  JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'beta' AND c.relkind IN ('r', 'p')
),
table_parts AS (
  SELECT t.oid, t.schema_name, t.table_name, a.attnum AS sort_order,
         pg_catalog.format('%I %s%s%s%s', a.attname,
           pg_catalog.format_type(a.atttypid, a.atttypmod),
           CASE a.attidentity
             WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
             WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY'
             ELSE '' END,
           CASE WHEN a.attgenerated <> '' THEN
             pg_catalog.format(' GENERATED ALWAYS AS (%s) STORED', pg_catalog.pg_get_expr(d.adbin, d.adrelid))
             WHEN d.adbin IS NOT NULL AND a.attidentity = '' THEN
             pg_catalog.format(' DEFAULT %s', pg_catalog.pg_get_expr(d.adbin, d.adrelid))
             ELSE '' END,
           CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END) AS definition
  FROM target_tables t
  JOIN pg_catalog.pg_attribute a ON a.attrelid = t.oid
  LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
  WHERE a.attnum > 0 AND NOT a.attisdropped

  UNION ALL

  SELECT t.oid, t.schema_name, t.table_name, 100000 + row_number() OVER (PARTITION BY t.oid ORDER BY c.conname),
         pg_catalog.format('CONSTRAINT %I %s', c.conname, pg_catalog.pg_get_constraintdef(c.oid, true))
  FROM target_tables t
  JOIN pg_catalog.pg_constraint c ON c.conrelid = t.oid
),
objects AS (
  SELECT '00 schema' AS section, 'beta' AS object_name,
         'CREATE SCHEMA IF NOT EXISTS beta;' AS definition

  UNION ALL

  SELECT '01 extension', e.extname,
         pg_catalog.format('CREATE EXTENSION IF NOT EXISTS %I WITH SCHEMA %I;', e.extname, n.nspname)
  FROM pg_catalog.pg_extension e
  JOIN pg_catalog.pg_namespace n ON n.oid = e.extnamespace
  WHERE e.extname = 'vector'

  UNION ALL

  SELECT '02 sequence', pg_catalog.format('%I.%I', n.nspname, s.relname),
         pg_catalog.format('CREATE SEQUENCE IF NOT EXISTS %I.%I AS %s INCREMENT BY %s MINVALUE %s MAXVALUE %s START WITH %s CACHE %s%s;',
           n.nspname, s.relname, pg_catalog.format_type(q.seqtypid, NULL), q.seqincrement, q.seqmin, q.seqmax,
           q.seqstart, q.seqcache, CASE WHEN q.seqcycle THEN ' CYCLE' ELSE '' END)
  FROM pg_catalog.pg_class s
  JOIN pg_catalog.pg_namespace n ON n.oid = s.relnamespace
  JOIN pg_catalog.pg_sequence q ON q.seqrelid = s.oid
  WHERE n.nspname = 'beta' AND s.relkind = 'S'

  UNION ALL

  SELECT '03 enum type', pg_catalog.format('%I.%I', n.nspname, t.typname),
         pg_catalog.format('CREATE TYPE %I.%I AS ENUM (%s);', n.nspname, t.typname,
           string_agg(pg_catalog.quote_literal(e.enumlabel), ', ' ORDER BY e.enumsortorder))
  FROM pg_catalog.pg_type t
  JOIN pg_catalog.pg_namespace n ON n.oid = t.typnamespace
  JOIN pg_catalog.pg_enum e ON e.enumtypid = t.oid
  WHERE n.nspname = 'beta'
  GROUP BY n.nspname, t.typname

  UNION ALL

  SELECT '04 table', pg_catalog.format('%I.%I', p.schema_name, p.table_name),
         pg_catalog.format('CREATE TABLE %I.%I (\n    %s\n);', p.schema_name, p.table_name,
           string_agg(p.definition, E',\n    ' ORDER BY p.sort_order))
  FROM table_parts p
  GROUP BY p.oid, p.schema_name, p.table_name

  UNION ALL

  SELECT '05 sequence ownership', pg_catalog.format('%I.%I', seq_ns.nspname, seq.relname),
         pg_catalog.format('ALTER SEQUENCE %I.%I OWNED BY %I.%I.%I;', seq_ns.nspname, seq.relname,
           table_ns.nspname, tbl.relname, a.attname)
  FROM pg_catalog.pg_class seq
  JOIN pg_catalog.pg_namespace seq_ns ON seq_ns.oid = seq.relnamespace
  JOIN pg_catalog.pg_depend d ON d.objid = seq.oid AND d.classid = 'pg_catalog.pg_class'::regclass
    AND d.refclassid = 'pg_catalog.pg_class'::regclass AND d.deptype IN ('a', 'i')
  JOIN pg_catalog.pg_class tbl ON tbl.oid = d.refobjid
  JOIN pg_catalog.pg_namespace table_ns ON table_ns.oid = tbl.relnamespace
  JOIN pg_catalog.pg_attribute a ON a.attrelid = tbl.oid AND a.attnum = d.refobjsubid
  WHERE seq_ns.nspname = 'beta' AND seq.relkind = 'S'

  UNION ALL

  SELECT '06 index', pg_catalog.format('%I.%I', i.schemaname, i.indexname), i.indexdef || ';'
  FROM pg_catalog.pg_indexes i
  WHERE i.schemaname = 'beta'
    AND NOT EXISTS (
      SELECT 1 FROM pg_catalog.pg_class ix
      JOIN pg_catalog.pg_namespace n ON n.oid = ix.relnamespace
      JOIN pg_catalog.pg_constraint c ON c.conindid = ix.oid
      WHERE n.nspname = i.schemaname AND ix.relname = i.indexname
    )

  UNION ALL

  SELECT '07 row security', pg_catalog.format('%I.%I', t.schema_name, t.table_name),
         pg_catalog.format('ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY;%s', t.schema_name, t.table_name,
           CASE WHEN t.relforcerowsecurity THEN pg_catalog.format(E'\nALTER TABLE %I.%I FORCE ROW LEVEL SECURITY;', t.schema_name, t.table_name) ELSE '' END)
  FROM target_tables t
  WHERE t.relrowsecurity

  UNION ALL

  SELECT '08 policy', pg_catalog.format('%I.%I.%I', p.schemaname, p.tablename, p.policyname),
         pg_catalog.format('CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;', p.policyname, p.schemaname, p.tablename,
           p.permissive, p.cmd, array_to_string(p.roles, ', '),
           CASE WHEN p.qual IS NOT NULL THEN pg_catalog.format(' USING (%s)', p.qual) ELSE '' END,
           CASE WHEN p.with_check IS NOT NULL THEN pg_catalog.format(' WITH CHECK (%s)', p.with_check) ELSE '' END)
  FROM pg_catalog.pg_policies p
  WHERE p.schemaname = 'beta'

  UNION ALL

  SELECT '09 schema grant', pg_catalog.format('%I -> %s (%s)', n.nspname,
           CASE WHEN acl.grantee = 0 THEN 'PUBLIC' ELSE r.rolname END, acl.privilege_type),
         pg_catalog.format('GRANT %s ON SCHEMA %I TO %s%s;', acl.privilege_type, n.nspname,
           CASE WHEN acl.grantee = 0 THEN 'PUBLIC' ELSE pg_catalog.quote_ident(r.rolname) END,
           CASE WHEN acl.is_grantable THEN ' WITH GRANT OPTION' ELSE '' END)
  FROM pg_catalog.pg_namespace n
  CROSS JOIN LATERAL pg_catalog.aclexplode(COALESCE(n.nspacl, pg_catalog.acldefault('n', n.nspowner))) acl
  LEFT JOIN pg_catalog.pg_roles r ON r.oid = acl.grantee
  WHERE n.nspname = 'beta'

  UNION ALL

  SELECT '10 table grant', pg_catalog.format('%I.%I -> %s (%s)', g.table_schema, g.table_name, g.grantee, g.privilege_type),
         pg_catalog.format('GRANT %s ON TABLE %I.%I TO %s%s;', g.privilege_type, g.table_schema, g.table_name,
           CASE WHEN g.grantee = 'PUBLIC' THEN 'PUBLIC' ELSE pg_catalog.quote_ident(g.grantee) END,
           CASE WHEN g.is_grantable = 'YES' THEN ' WITH GRANT OPTION' ELSE '' END)
  FROM information_schema.role_table_grants g
  WHERE g.table_schema = 'beta'

  UNION ALL

  SELECT '11 function', pg_catalog.format('%I.%I', n.nspname, p.proname), pg_catalog.pg_get_functiondef(p.oid)
  FROM pg_catalog.pg_proc p
  JOIN pg_catalog.pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'beta' AND p.prokind IN ('f', 'p')

  UNION ALL

  SELECT '12 trigger', pg_catalog.format('%I.%I.%I', n.nspname, c.relname, t.tgname),
         pg_catalog.pg_get_triggerdef(t.oid, true) || ';'
  FROM pg_catalog.pg_trigger t
  JOIN pg_catalog.pg_class c ON c.oid = t.tgrelid
  JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'beta' AND NOT t.tgisinternal
)
SELECT section, object_name, definition
FROM objects
ORDER BY section, object_name;
